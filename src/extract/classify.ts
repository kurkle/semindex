export type Lang = 'ts' | 'tsx' | 'js' | 'jsx' | 'md' | 'mdx'

export interface FileClass {
  lang: Lang
  /** Test, mock or fixture code. Indexed, but kept out of production comparisons. */
  test: boolean
}

const LANGS: Record<string, Lang> = {
  '.ts': 'ts',
  '.mts': 'ts',
  '.cts': 'ts',
  '.tsx': 'tsx',
  '.js': 'js',
  '.mjs': 'js',
  '.cjs': 'js',
  '.jsx': 'jsx',
  '.md': 'md',
  '.mdx': 'mdx',
}

/** Paths that are generated or vendored by convention; their files are not indexed. */
const SKIP_PATH =
  /(^|\/)(node_modules|vendor|vendored|third_party|generated|__generated__|dist|build|coverage|\.next|\.astro|\.svelte-kit)\//

const SKIP_FILE = /(\.d\.[cm]?ts|\.min\.js|\.bundle\.js|-lock\.json|\.map)$/

const TEST_PATH =
  /(\.(test|spec|stories)\.[cm]?[jt]sx?$)|(^|\/)(__tests__|__mocks__|__mockData__|__fixtures__|test|tests|e2e|fixtures|test-utils)\//

export function classifyPath(path: string): FileClass | null {
  const dot = path.lastIndexOf('.')
  const lang = dot >= 0 ? LANGS[path.slice(dot).toLowerCase()] : undefined
  if (!lang) return null
  if (SKIP_PATH.test(path) || SKIP_FILE.test(path)) return null
  return { lang, test: TEST_PATH.test(path) || /(^|\/)test-utils\.[jt]sx?$/.test(path) }
}

/**
 * Content rules for generated or vendored files that live outside the conventional folders:
 * a generated-file marker near the top, or minified code (very long lines).
 */
export function isGeneratedContent(text: string): boolean {
  const head = text.slice(0, 1000)
  if (/@generated\b|\bDO NOT EDIT\b|auto-generated|autogenerated/i.test(head)) return true
  const lines = text.split('\n')
  if (lines.length === 0) return false
  const long = lines.filter((l) => l.length > 500).length
  return long > 0 && long / lines.length > 0.1
}
